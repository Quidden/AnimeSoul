export function Toggle({
  label,
  value,
  onChange,
}: {
  label: string;
  value: boolean;
  onChange: (value: boolean) => void;
}) {
  const help: Record<string, string> = {
    "Автоскип опенинга": "Перематывает опенинг автоматически, если источник передал его точный таймкод.",
    "Автоскип эндинга": "Перематывает эндинг и корректно завершает просмотр серии.",
    "Автосерия": "После окончания запускает следующую доступную серию.",
    "Переход к плееру": "При ручном выборе серии плавно прокручивает страницу к плееру.",
    "Карусель серий": "Показывает предыдущую и следующую серии по сторонам плеера.",
    "Предпросмотр серии при наведении": "После короткой задержки показывает доступные кадры выбранной серии.",
    "Компактная панель (только иконки)": "Скрывает подписи и текущие значения на панели плеера, оставляя кнопки с подсказками.",
    "Автоматически запускать продолжение": "Запускает серию с сохранённого момента сразу после перехода.",
    "Предпросмотр серии на главной": "Заменяет обычную кнопку продолжения визуальной карточкой серии.",
    "Сохранять историю": "Добавляет просмотры в историю; прогресс сохраняется и при выключенной истории.",
  };
  const description = help[label];
  return (
    <label className="toggle-row" data-help={description}>
      <button
        type="button"
        className={value ? "toggle on" : "toggle"}
        aria-pressed={value}
        onClick={() => onChange(!value)}
      >
        <i />
      </button>
      <span>{label}</span>
    </label>
  );
}
